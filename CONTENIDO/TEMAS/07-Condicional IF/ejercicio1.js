// Condicional IF
// El condicional IF se utiliza para ejecutar un bloque de código si una condición es verdadera.

// Sintaxis:
// if (condición) {
//     // código a ejecutar si la condición es verdadera
// }    
//     else {
//   código a ejecutar si la condición es falsa

// Ejercicio 1
let Llueve = true;

if (Llueve === true) { // si la variable Llueve es igual a true, entonces se ejecuta el bloque de código

    console.log("Lleva un paraguas"); 

} else { // si la condición es falsa, entonces se ejecuta el bloque de código del else

    console.log("No lleves un paraguas");

}